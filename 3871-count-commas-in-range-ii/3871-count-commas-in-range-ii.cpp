class Solution {
public:
    long long countCommas(long long n) {
       if(n<1000) return 0;
       if(n<1000000) return n-999;
       if(n<1000000000) return 2*(n-999999)+1000000-1000;
        if(n<1000000000000) return 3*(n-999999999)+2*1000000000-1000-1000000;
        if(n<1000000000000000) return 4*(n-999999999999)+(3*1000000000000)-1000-1000000-1000000000;
        return 4*(n-999999999999)+(3*1000000000000)-1000-1000000-1000000000+1;
    }
};